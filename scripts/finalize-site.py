"""Package static CSS, crawl files and CSP after authoring the HTML pages."""
from pathlib import Path
import re
import json
import hashlib
import base64
import os
from urllib.parse import urlparse

ROOT=Path(__file__).resolve().parent.parent
site_url=os.environ.get('SOUDYN_SITE_URL','https://soudynlabs.com').rstrip('/')
endpoint=os.environ.get('SOUDYN_FORM_ENDPOINT','')
if not site_url.startswith('https://'): raise ValueError('Use an HTTPS site URL')
if endpoint and (urlparse(endpoint).scheme != 'https' or not urlparse(endpoint).netloc):
    raise ValueError('Form endpoint must be an absolute HTTPS URL')

def read_css(name):
    text=(ROOT/'assets/css'/name).read_text()
    return re.sub(r'@import[^;]+;', '', text)

def minify(text):
    text=re.sub(r'/\*.*?\*/','',text,flags=re.S)
    return re.sub(r'\s*([{};:,])\s*',r'\1',re.sub(r'\s+',' ',text)).strip()

sources=['tokens.css','font-fallbacks.css','base.css','components.css','pages.css']
combined=minify('\n'.join(read_css(name) for name in sources))
(ROOT/'assets/css/site.css').write_text('/* Generated by scripts/finalize-site.py. Edit the source CSS files. */\n'+combined+'\n',encoding='ascii')
hashes=set()
critical=minify('\n'.join(read_css(name) for name in sources[:3]))
if len(combined.encode())>14336:
    p=ROOT/'index.html';text=p.read_text()
    text=re.sub(r'<style data-critical>.*?</style>','',text,flags=re.S)
    text=text.replace('<link rel="stylesheet"',f'<style data-critical>{critical}</style><link rel="stylesheet"',1)
    p.write_text(text,encoding='ascii')

def digest(text): return "'sha256-"+base64.b64encode(hashlib.sha256(text.encode()).digest()).decode()+"'"

style_hashes=set()
for p in ROOT.rglob('*.html'):
    if '.tools' in p.parts or '.git' in p.parts: continue
    text=p.read_text()
    hashes.update(digest(s) for s in re.findall(r'<script type="application/ld\+json">(.*?)</script>',text,re.S))
    style_hashes.update(digest(s) for s in re.findall(r'<style data-critical>(.*?)</style>',text,re.S))
    # Content versions prevent immutable assets remaining stale after edits.
    text=re.sub(r'((?:href|src)="/assets/(?:css|js)/[^"?]+)(?:\?v=[a-f0-9]+)?"',lambda m:m[1]+'?v='+hashlib.sha256((ROOT/m[1].split('"/')[1]).read_bytes()).hexdigest()[:12]+'"',text)
    p.write_text(text,encoding='ascii')

provider=''
if endpoint:
    parsed=urlparse(endpoint);provider=parsed.scheme+'://'+parsed.netloc
config="window.SOUDYN = "+json.dumps({'siteUrl':site_url,'formEndpoint':endpoint,'analytics':''},indent=2)+";\n// [CONFIRM production domain, form endpoint and analytics provider or none]\n"
# Write config before the final asset version pass below.
(ROOT/'assets/js/config.js').write_text(config,encoding='ascii')
for p in ROOT.rglob('*.html'):
    if '.tools' in p.parts or '.git' in p.parts: continue
    s=p.read_text();s=re.sub(r'(/assets/js/config.js)\?v=[a-f0-9]+',lambda m:m[1]+'?v='+hashlib.sha256(config.encode()).hexdigest()[:12],s);p.write_text(s,encoding='ascii')

csp=("default-src 'self'; img-src 'self' data:; style-src 'self' "+' '.join(sorted(style_hashes))+"; script-src 'self' "+' '.join(sorted(hashes))+"; font-src 'self'; connect-src 'self'"+(' '+provider if provider else '')+"; form-action 'self'"+(' '+provider if provider else '')+"; base-uri 'self'; frame-ancestors 'none'; object-src 'none'")
headers=[{'key':k,'value':v} for k,v in [('X-Content-Type-Options','nosniff'),('Referrer-Policy','strict-origin-when-cross-origin'),('X-Frame-Options','DENY'),('Permissions-Policy','camera=(), microphone=(), geolocation=()'),('Content-Security-Policy',csp)]]
vercel={'buildCommand':'node scripts/package-site.mjs','outputDirectory':'dist','cleanUrls':True,'trailingSlash':True,'headers':[{'source':'/(.*)','headers':headers},{'source':'/assets/(.*)','headers':[{'key':'Cache-Control','value':'public, max-age=31536000, immutable'}]}]}
(ROOT/'vercel.json').write_text(json.dumps(vercel,indent=2)+'\n',encoding='ascii')
(ROOT/'robots.txt').write_text('User-agent: *\nDisallow: /\n',encoding='ascii')
paths=['/','/services.html','/products.html','/travelos.html','/work.html','/about.html','/contact.html']
sitemap='<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'+''.join(f'  <url><loc>{site_url}{path}</loc><lastmod>2026-10-25</lastmod></url>\n' for path in paths)+'</urlset>\n'
(ROOT/'sitemap.xml').write_text(sitemap,encoding='ascii')
manifest={'name':'Soudyn Labs','short_name':'Soudyn Labs','start_url':'/','display':'browser','background_color':'#0F1F3D','theme_color':'#0F1F3D','icons':[{'src':'/assets/img/icon-512.png','sizes':'512x512','type':'image/png'}]}
(ROOT/'site.webmanifest').write_text(json.dumps(manifest,indent=2)+'\n',encoding='ascii')
print('Static CSS, metadata asset versions, CSP hashes, config, staging robots and sitemap prepared.')
