import { chromium } from '../../.tools/browser/node_modules/playwright-core/index.mjs';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const base = 'http://127.0.0.1:4174';
const page = await browser.newPage({viewport:{width:390,height:844}});
const errors=[]; page.on('pageerror', e=>errors.push(e.message));
await page.goto(base+'/components-test.html');
await page.getByRole('button',{name:'Menu',exact:true}).click();
assert.equal(await page.locator('.menu-button').getAttribute('aria-expanded'),'true');
assert.equal(await page.locator('main').evaluate(e=>e.inert),true);
assert.equal(await page.evaluate(()=>document.activeElement.textContent),'Services');
await page.locator('#site-navigation a').last().focus();await page.keyboard.press('Tab');
assert.equal(await page.evaluate(()=>document.activeElement.textContent),'Close');
await page.keyboard.press('Shift+Tab');
assert.equal(await page.evaluate(()=>document.activeElement.textContent),'Start a project');
await page.keyboard.press('Escape');
assert.equal(await page.locator('.menu-button').getAttribute('aria-expanded'),'false');
assert.equal(await page.locator('main').evaluate(e=>e.inert),false);
assert.equal(await page.evaluate(()=>document.activeElement.textContent),'Menu');
await page.locator('summary').first().focus();await page.keyboard.press('Enter');
assert.equal(await page.locator('details').first().getAttribute('open'),'');
await page.evaluate(fs.readFileSync('.tools/browser/node_modules/axe-core/axe.min.js','utf8'));
const axe=await page.evaluate(async()=>{const r=await axe.run();return r.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)}));});
assert.deepEqual(axe,[]);
assert.deepEqual(errors,[]);
console.log('PASS: menu focus trap, Escape/restore, inert background, keyboard accordion, axe (no violations), JS errors');
await page.screenshot({path:'.tools/components-mobile.png',fullPage:true});
await browser.close();
